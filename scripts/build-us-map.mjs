// Generates src/usMap.js: every US state as an SVG path in the pre-projected Albers USA layout
// (us-atlas states-albers-10m.json, 975x610). Run: node scripts/build-us-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoPath } from 'd3-geo';

const topo = JSON.parse(readFileSync(new URL('../node_modules/us-atlas/states-albers-10m.json', import.meta.url), 'utf8'));
const states = feature(topo, topo.objects.states).features;
const path = geoPath(); // already projected
const PAIR = /(-?\d+\.?\d*),(-?\d+\.?\d*)/g;

const out = states.map((f) => {
  const d = path(f) || '';
  const parts = d.split('M').filter(Boolean).map((q) => 'M' + q);
  // drop islands under 2 units, then decimate: keep a point only when it moved >= 1.5 units
  const slim = parts.map((q) => [...q.matchAll(PAIR)].map((t) => [+t[1], +t[2]])).filter((pts) => {
    const xs = pts.map((p) => p[0]);
    const ys = pts.map((p) => p[1]);
    return Math.max(...xs) - Math.min(...xs) > 2 || Math.max(...ys) - Math.min(...ys) > 2;
  }).map((pts) => {
    const keep = [];
    for (const p of pts) {
      const last = keep[keep.length - 1];
      if (!last || Math.abs(p[0] - last[0]) + Math.abs(p[1] - last[1]) >= 1.5) keep.push(p);
    }
    return 'M' + keep.map((p) => p[0].toFixed(0) + ',' + p[1].toFixed(0)).join('L') + 'Z';
  });
  return { id: f.id, name: f.properties.name, d: slim.join('') };
}).filter((s) => s.d);

const body = out.map((s) => `  { id: ${JSON.stringify(s.id)}, name: ${JSON.stringify(s.name)}, d: ${JSON.stringify(s.d)} },`).join('\n');
writeFileSync(
  new URL('../src/usMap.js', import.meta.url),
  `// Generated by scripts/build-us-map.mjs — do not edit by hand.\nexport const US_VIEWBOX = '0 0 975 610';\nexport const usStates = [\n${body}\n];\n`
);
console.log('wrote', out.length, 'states');
