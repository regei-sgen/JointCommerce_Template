// Generates src/stateShapes.js: one SVG path (in a 100x100 box) per state listed in src/data.js.
// Source: us-atlas states-10m.json (US Census TIGER, ISC-licensed package). Run: node scripts/build-state-shapes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoPath, geoMercator } from 'd3-geo';

const topo = JSON.parse(readFileSync(new URL('../node_modules/us-atlas/states-10m.json', import.meta.url), 'utf8'));
const states = feature(topo, topo.objects.states).features;
const src = readFileSync(new URL('../src/data.js', import.meta.url), 'utf8');
const m = src.match(/export const states = \[([\s\S]*?)\];/);
if (!m) throw new Error('states array not found in src/data.js');
const wanted = [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]);

const PAIR = /(-?\d+\.?\d*),(-?\d+\.?\d*)/g;
const out = {};
for (const name of wanted) {
  const f = states.find((s) => s.properties.name === name);
  if (!f) throw new Error('state not in atlas: ' + name);
  const proj = geoMercator().fitExtent([[4, 4], [96, 96]], f);
  const d = geoPath(proj)(f);
  // keep only subpaths wider or taller than 3 units (drops small islands), then round to 1 decimal
  const parts = d.split('M').filter(Boolean).map((q) => 'M' + q);
  const big = parts.filter((q) => {
    const pts = [...q.matchAll(PAIR)];
    const xs = pts.map((t) => +t[1]);
    const ys = pts.map((t) => +t[2]);
    return Math.max(...xs) - Math.min(...xs) > 3 || Math.max(...ys) - Math.min(...ys) > 3;
  });
  out[name] = big.join('').replace(/(\d+\.\d)\d+/g, '$1');
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(
  new URL('../src/stateShapes.js', import.meta.url),
  `// Generated by scripts/build-state-shapes.mjs — do not edit by hand.\n// Each path fits a 100x100 viewBox.\nexport const stateShapes = {\n${body}\n};\n`
);
console.log('wrote', Object.keys(out).length, 'shapes');
